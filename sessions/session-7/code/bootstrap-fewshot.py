"""The simplest optimizer (§4): BootstrapFewShot fills the demos slot.

The optimizer runs the program over the trainset with tracing on, calls the
metric with the trace, and keeps every run the metric accepts as a
demonstration. Session 6's `trace is not None` branch runs here for the first
time. Nothing else changes: the instructions stay as written, and the
result is the same module with `predict.demos` filled.

Part two adds a validation split. BootstrapFewShotWithRandomSearch builds
several candidate demo sets and keeps the one that scores best on val.
"""

import random

import dspy

from common import (STATE, TASK_LM, UnixAssistant, command_match, cost, load_unix)

dspy.configure(lm=TASK_LM)

trainset, valset, testset = load_unix("train"), load_unix("val"), load_unix("test")
random.Random(3).shuffle(trainset)   # fixed order, so the run is repeatable

# Wrap the metric to watch it being called in bootstrap mode.
verdicts = []


def watched_metric(example, pred, trace=None):
    verdict = command_match(example, pred, trace)
    verdicts.append((example.request, pred.command, trace is not None, verdict))
    return verdict


optimizer = dspy.BootstrapFewShot(
    metric=watched_metric,
    max_bootstrapped_demos=4,   # demos generated by running the program
    max_labeled_demos=4,        # total demos; trainset rows fill any remainder
)
optimized = optimizer.compile(UnixAssistant(), trainset=trainset)

print("--- metric calls during compile ---")
for request, command, traced, verdict in verdicts:
    print(f"trace={'yes' if traced else 'no ':3s} {str(verdict):5s} {request[:38]:38s} -> {command}")
kept = sum(1 for *_, verdict in verdicts if verdict)
print(f"{len(verdicts)} calls, {kept} accepted; stopped once 4 bootstrapped demos were in hand")

print("\n--- what the optimizer wrote ---")
state = optimized.dump_state()
print(f"instructions : {state['predict']['signature']['instructions']!r}  (unchanged)")
print(f"demos        : {len(state['predict']['demos'])}")
for demo in state["predict"]["demos"]:
    kind = "bootstrapped" if demo.get("augmented") else "labeled"
    print(f"  [{kind:12s}] {demo['request'][:40]:40s} -> {demo['command']}")

evaluator = dspy.Evaluate(devset=testset, metric=command_match, num_threads=4)
print("\n--- test split, before and after ---")
print(f"baseline     : {evaluator(UnixAssistant()).score}")
print(f"bootstrapped : {evaluator(optimized).score}")

# Part two: the same idea, many times, with a validation split to choose by.
print("\n--- random search over demo sets, chosen on val ---")
search = dspy.BootstrapFewShotWithRandomSearch(
    metric=command_match,
    max_bootstrapped_demos=4,
    max_labeled_demos=4,
    num_candidate_programs=6,
    num_threads=4,
)
best = search.compile(UnixAssistant(), trainset=trainset, valset=valset)
for candidate in best.candidate_programs:
    print(f"seed {candidate['seed']:>2}  val {candidate['score']:>6.2f}  "
          f"demos {len(candidate['program'].predict.demos)}")
print(f"best on val  : {best.candidate_programs[0]['score']}")
print(f"best on test : {evaluator(best).score}")

STATE.mkdir(exist_ok=True)
optimized.save(STATE / "unix-bootstrap.json")
best.save(STATE / "unix-bootstrap-rs.json")
print(f"\nsaved to {STATE.name}/unix-bootstrap.json and unix-bootstrap-rs.json")
print(f"cost         : ${cost(TASK_LM):.4f} task model")

